#pragma once
#include "db.hpp"

/**
 * @brief Версия схемы, которую создаёт эта сборка (число миграций).
 */
[[nodiscard]] int schema_version();

/**
 * @brief Текущая версия схемы в базе (PRAGMA user_version), 0 для пустой базы.
 */
[[nodiscard]] int current_schema_version(Database &db);

/**
 * @brief Применяет недостающие миграции, каждую в своей транзакции.
 *
 * На время миграции внешние ключи выключаются (пересборка таблиц), перед фиксацией каждой миграции
 * проверяется ссылочная целостность.
 * @param target версия, до которой мигрировать (для тестов промежуточных версий)
 * @throws DbError если база создана более новой версией программы или миграция нарушила целостность
 * @return версия схемы после миграции
 */
int migrate(Database &db, int target = schema_version());
