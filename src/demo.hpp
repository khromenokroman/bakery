#pragma once
#include <cstdint>
#include <string>

#include "db.hpp"

/// Пароль демонстрационных пользователей admin, tech и seller.
constexpr char const DEMO_PASSWORD[] = "demo123";

/**
 * @brief Сколько создано при заполнении демонстрационной базы.
 */
struct DemoStats {
    std::int64_t items{};    ///< позиций номенклатуры всех видов
    std::int64_t partners{}; ///< клиентов
    std::int64_t docs{};     ///< документов
    std::int64_t admin_id{}; ///< пользователь admin
};

/**
 * @brief Заполняет пустую базу демонстрационными данными за год до today.
 *
 * Группы, около 380 позиций (сырьё, полуфабрикаты, продукция) с рецептурами, типы цен «Себестоимость»,
 * «Розница» и «Опт» с переоценками раз в квартал, 100 клиентов, реквизиты; по дням заявки, поступление,
 * реализации (часть строк не по типовой цене), возвраты, списания, инвентаризации раз в месяц; в последний
 * день - черновик реализации и заявка на завтра. Пользователи admin (администратор), tech (технолог),
 * seller (продавец) с паролем DEMO_PASSWORD; авторы документов - технолог и продавец. Признак demo в settings.
 *
 * Данные создаются обычными классами в одной транзакции и в порядке времени: остатки не уходят в минус,
 * перепроведение не требуется; при ошибке база остаётся пустой. Генератор детерминирован.
 * @param today "ГГГГ-ММ-ДД": последний день данных
 * @param days за сколько дней документы (для тестов - меньше года)
 * @throws UserError база не пустая
 */
DemoStats fill_demo(Database &db, std::string const &today, int days = 365);

/// База заполнена демонстрационными данными (признак demo в settings).
[[nodiscard]] bool is_demo(Database &db);
